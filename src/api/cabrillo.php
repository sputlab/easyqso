<?php
// ============================================================
//  EasyQSO — Export Cabrillo  (api/cabrillo.php)
//  Formato standard per invio log contest
// ============================================================
header('Access-Control-Allow-Origin: *');
header('Access-Control-Allow-Headers: Content-Type, Authorization');
if ($_SERVER['REQUEST_METHOD']==='OPTIONS'){http_response_code(204);exit;}

require_once __DIR__.'/../includes/auth.php';
$user = require_auth();

$contest  = preg_replace('/[^A-Z0-9\-_]/i','', $_GET['contest'] ?? 'CQ-WW-SSB');
$category = preg_replace('/[^A-Z0-9\-_]/i','', $_GET['category'] ?? 'SINGLE-OP');
$power    = preg_replace('/[^A-Z]/','', strtoupper($_GET['power'] ?? 'HIGH'));
$band_cat = preg_replace('/[^A-Z0-9]/','', strtoupper($_GET['band'] ?? 'ALL'));

$st = db()->prepare(
    'SELECT * FROM eqso_qso_log WHERE user_id=? ORDER BY qso_date ASC, qso_time ASC'
);
$st->execute([$user['id']]);
$qsos = $st->fetchAll();

if (!$qsos) {
    header('Content-Type: application/json');
    echo json_encode(['ok'=>false,'error'=>'Nessun QSO da esportare.']);
    exit;
}

$mycall = strtoupper($user['callsign']);
$now    = date('Y-m-d H:i');

// Mappa banda → frequenza Cabrillo (kHz, valore rappresentativo)
$band_khz = [
    '160m'=>1800,'80m'=>3500,'40m'=>7000,'30m'=>10100,
    '20m'=>14000,'17m'=>18068,'15m'=>21000,'12m'=>24890,
    '10m'=>28000,'6m'=>50000,'2m'=>144000,'70cm'=>432000,
];

// Mappa modo ADIF → Cabrillo
$mode_cab = [
    'SSB'=>'PH','FM'=>'PH','AM'=>'PH',
    'CW'=>'CW',
    'FT8'=>'DI','FT4'=>'DI','DIGI'=>'DI','RTTY'=>'RY','PSK31'=>'DI',
];

header('Content-Type: text/plain; charset=UTF-8');
header('Content-Disposition: attachment; filename="'.strtolower($mycall).'_'.strtolower($contest).'.cbr"');

// ── Header Cabrillo ──────────────────────────────────────────
echo "START-OF-LOG: 3.0\r\n";
echo "CREATED-BY: EasyQSO v2.1.2\r\n";
echo "CONTEST: {$contest}\r\n";
echo "CALLSIGN: {$mycall}\r\n";
echo "CATEGORY-OPERATOR: {$category}\r\n";
echo "CATEGORY-POWER: {$power}\r\n";
echo "CATEGORY-BAND: {$band_cat}\r\n";
echo "CATEGORY-MODE: MIXED\r\n";
echo "CLAIMED-SCORE: 0\r\n";
echo "OPERATORS: {$mycall}\r\n";
echo "NAME: EasyQSO Logger\r\n";
echo "ADDRESS: sputlab.com\r\n";
echo "CREATED: {$now}\r\n";
echo "SOAPBOX: Generated by EasyQSO v2.1.2 (sputlab.com)\r\n";

$serial = 1;
foreach ($qsos as $q) {
    $freq_khz = $band_khz[strtolower($q['band'])] ?? 14000;
    if ($q['freq']) $freq_khz = (int)round((float)$q['freq'] * 1000);

    $mode = $mode_cab[strtoupper($q['mode'])] ?? 'PH';

    // Data e ora: YYYY-MM-DD HHMM
    $date = $q['qso_date'];
    $time = str_replace(':','',substr($q['qso_time'],0,5));

    $rst_s = str_pad($q['rst_sent']??'59', 3);
    $rst_r = str_pad($q['rst_rcvd']??'59', 3);
    $ser_s = str_pad($q['serial_sent'] ?? sprintf('%03d',$serial), 6);
    $ser_r = str_pad($q['serial_rcvd'] ?? '001', 6);
    $dx    = str_pad(strtoupper($q['callsign']),13);

    // QSO: freq  mode  date      time   mycall        rst  ser   dxcall       rst  ser
    printf("QSO: %6d %-2s %s %s %-13s %s %s %s %s %s\r\n",
        $freq_khz, $mode, $date, $time,
        $mycall, $rst_s, $ser_s,
        $dx, $rst_r, $ser_r
    );
    $serial++;
}

echo "END-OF-LOG:\r\n";
exit;
